const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file));
const pages = ['index.html', 'Life sim relationships .html'];
const manifest = JSON.parse(read('manifest.webmanifest'));
const assets = new Set([...pages, ...manifest.icons.map(icon => icon.src)]);
for (const page of pages) {
  for (const [, url] of read(page).toString().matchAll(/<(?:link|script)\b[^>]*\b(?:href|src)="([^"]+)"/gi)) {
    const asset = new URL(url, 'https://app.example/');
    if (asset.origin === 'https://app.example') assets.add(decodeURIComponent(asset.pathname.slice(1)));
  }
}

const files = [...assets].sort();
const hash = createHash('sha256');
for (const file of [...files, 'offline-worker.js']) {
  const contents = read(file);
  hash.update(JSON.stringify([file, contents.length])).update(contents);
}
const output = '// Generated by npm run offline:build.\n' +
  'const OFFLINE_VERSION = ' + JSON.stringify(hash.digest('hex').slice(0, 20)) + ';\n' +
  'const OFFLINE_ASSETS = ' + JSON.stringify(files, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (read('offline-assets.js').toString() !== output) {
    console.error('Offline assets are out of date. Run npm run offline:build.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(path.join(root, 'offline-assets.js'), output);
}
